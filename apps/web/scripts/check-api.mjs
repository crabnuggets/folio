import { readFile } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';

const target = new URL('../src/lib/schema.d.ts', import.meta.url);
const result = astToString(await openapiTS(new URL('../../../api/openapi.yaml', import.meta.url)));
// The CLI prepends this same generated-file notice.
const expected = await readFile(target, 'utf8');
const normalize = (text) => text.replace(/\r\n/g, '\n')
  .replace(/^\/\*\*\n \* This file was auto-generated by openapi-typescript\.[\s\S]*?\*\/\s*/, '').trim();
if (normalize(expected) !== normalize(result)) {
  throw new Error('OpenAPI types are stale. Run npm run generate:api.');
}
console.log('OpenAPI types match the contract.');
